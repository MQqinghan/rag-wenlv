def extract_cities(text: str) -> list[str]:
    """从文本中抽取出现的城市名（名单子串匹配，去重保序）。

    Args:
        text: 问句 / 文件标题 / 正文摘要等任意文本。

    Returns:
        list[str]: 命中的标准城市名列表，可能为空。别名命中时展开为对应标准城市。
    """
    if not text:
        return []
    seen: list[str] = []
    for city in CITY_LIST:
        if city in text and city not in seen:
            seen.append(city)
    # 别名展开（如"潮汕"→潮州+汕头；已命中标准名的跳过）
    for alias, cities in REGION_ALIAS.items():
        if alias in text:
            for city in cities:
                if city not in seen:
                    seen.append(city)
    return seen


def build_region_like_expr(cities: list[str]) -> str:
    """把城市列表构建为 Milvus VARCHAR 的 region like 过滤表达式。

    每个城市同时匹配「城市名」与「所属省」（region 实测存在"海南三亚/四川成都"
    城市级与"海南/云南"省级两种粒度，双匹配避免小城市落空导致三路全空）。

    Args:
        cities: 标准城市名列表（extract_cities 的输出）。

    Returns:
        str: 如 'region like "%三亚%" or region like "%海南%"'；空列表返回空串。
    """
    if not cities:
        return ""
    keywords: list[str] = []
    for city in cities:
        if city not in keywords:
            keywords.append(city)
        province = CITY_TO_PROVINCE.get(city)
        if province and province not in keywords:
            keywords.append(province)
    clauses = [f'region like "%{kw}%"' for kw in keywords]
    return " or ".join(clauses)
